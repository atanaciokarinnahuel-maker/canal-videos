export const shotAt = (t: number) => {
  let i = 0;
  while (i < SHOTS.length - 1 && SHOTS[i + 1].t <= t) i++;
  const sh = SHOTS[i];
  const end = i < SHOTS.length - 1 ? SHOTS[i + 1].t : DUR;
  return {shot: sh, index: i, u: Math.min(1, Math.max(0, (t - sh.t) / Math.max(0.01, end - sh.t))), dur: end - sh.t};
};
